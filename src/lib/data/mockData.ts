function makeProperty(input: {
  id: string;
  slug: string;
  title: string;
  description: string;
  price: number;
  property_type: string;
  bhk: number;
  bathrooms: number;
  area_sqft: number;
  tenant_type: Property["tenant_type"];
  furnishing: string;
  address: string;
  featured?: boolean;
  video_url?: string;
  location: Location;
}) {
  const property: Property = {
    id: input.id,
    slug: input.slug,
    title: input.title,
    description: input.description,
    price: input.price,
    security_deposit: input.price * 2,
    maintenance: Math.round(input.price * 0.06),
    property_type: input.property_type,
    listing_type: "RENT",
    bhk: input.bhk,
    bathrooms: input.bathrooms,
    area_sqft: input.area_sqft,
    floor: 2,
    total_floors: 4,
    tenant_type: input.tenant_type,
    furnishing: input.furnishing,
    status: "AVAILABLE",
    location_id: input.location.id,
    address: input.address,
    latitude: null,
    longitude: null,
    featured: Boolean(input.featured),
    available_from: now,
    video_url: input.video_url || null,
    created_at: now,
    updated_at: now,
    location: input.location,
    images: [],
  };

  return property;
}

